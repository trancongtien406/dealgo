#!/usr/bin/env node
/**
 * Regenerates docs/06-data-api/rest-api.openapi.yaml from the Nest controllers.
 *
 * Usage (from backend/): npm run openapi:export
 *   = nest build && node scripts/export-openapi.mjs [--dist dist] [--out ../docs/06-data-api/rest-api.openapi.yaml]
 *
 * The app is created in Nest "preview" mode, so no database, Redis or provider connection is
 * opened. Hand-written response codes/descriptions already present in the output file are kept
 * for operations that still exist, and the /.well-known/* paths (served outside Swagger) are kept.
 */
import 'reflect-metadata';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import YAML from 'yaml';

const arg = (name, fallback) => {
  const i = process.argv.indexOf(name);
  return i > -1 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
};
const distDir = resolve(arg('--dist', 'dist'));
const outFile = resolve(arg('--out', '../docs/06-data-api/rest-api.openapi.yaml'));

process.env.NODE_ENV ??= 'development';
process.env.SWAGGER_ENABLED ??= 'true';

const { NestFactory } = await import('@nestjs/core');
const { AppModule } = await import(pathToFileURL(`${distDir}/app.module.js`).href);
const { buildOpenApiDocument } = await import(pathToFileURL(`${distDir}/platform/http/index.js`).href);

const app = await NestFactory.create(AppModule, { preview: true, logger: ['error'], abortOnError: false });
const doc = buildOpenApiDocument(app);
await app.close().catch(() => undefined);

const METHODS = ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace'];

if (existsSync(outFile)) {
  const previous = YAML.parse(readFileSync(outFile, 'utf8'));
  for (const [path, oldItem] of Object.entries(previous.paths ?? {})) {
    const item = doc.paths[path];
    if (!item) {
      if (path.startsWith('/.well-known/')) doc.paths[path] = oldItem;
      continue;
    }
    for (const method of METHODS) {
      const op = item[method];
      const oldOp = oldItem[method];
      if (!op || !oldOp?.responses) continue;
      op.responses ??= {};
      for (const [code, oldResponse] of Object.entries(oldOp.responses)) {
        const current = op.responses[code];
        if (!current) op.responses[code] = oldResponse;
        else if (!current.description && oldResponse.description) current.description = oldResponse.description;
      }
    }
  }
}

const sortedPaths = Object.fromEntries(Object.entries(doc.paths).sort(([a], [b]) => a.localeCompare(b)));
doc.paths = sortedPaths;
const { openapi, info, servers, tags, paths, components, ...rest } = doc;
const ordered = { openapi, info, ...(servers?.length ? { servers } : {}), tags, paths, components, ...rest };

const header = [
  '# Generated by backend/scripts/export-openapi.mjs from the Nest controllers. Do not edit by hand:',
  '# change the controller decorators and run `npm run openapi:export` in backend/.',
  '',
].join('\n');
writeFileSync(outFile, header + YAML.stringify(ordered, { lineWidth: 0 }));
const ops = Object.values(doc.paths).reduce((n, item) => n + METHODS.filter((m) => item[m]).length, 0);
console.log(`openapi: ${Object.keys(doc.paths).length} paths, ${ops} operations -> ${outFile}`);
process.exit(0);
