ALTER TABLE "payment_intents"
  ADD COLUMN IF NOT EXISTS "methodCode" VARCHAR(32),
  ADD COLUMN IF NOT EXISTS "providerTransId" VARCHAR(64),
  ADD COLUMN IF NOT EXISTS "providerPayDate" VARCHAR(20),
  ADD COLUMN IF NOT EXISTS "deeplink" VARCHAR(2000),
  ADD COLUMN IF NOT EXISTS "refundedVnd" INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS "failureReason" VARCHAR(255);

CREATE TABLE IF NOT EXISTS "payment_selections" (
  "entityType" "PaymentEntityType" NOT NULL,
  "entityId" UUID NOT NULL,
  "methodCode" VARCHAR(32) NOT NULL,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMP(3) NOT NULL,
  CONSTRAINT "payment_selections_pkey" PRIMARY KEY ("entityType", "entityId")
);
